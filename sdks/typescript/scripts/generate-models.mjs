// Generates the SDK's public model layer from the server's model catalogue (../models.json) and route manifest
// (../routes.json):
//
//   src/models.ts       The types the SDK hands to and takes from callers. A wire model (src/generated/, emitted by
//                       maitento/app/SdkModelGenerator) whose fields are all plain JSON is re-exported unchanged; one
//                       that carries a date or a .NET TimeSpan, directly or through a nested model, is re-declared
//                       over it with `Date` for dates and milliseconds for durations.
//   src/codec-table.ts  The field-level wire metadata the runtime codec (src/core/codec.ts) walks to make that true:
//                       which fields are dates / TimeSpans / nested models, and which models carry a discriminator
//                       that must be the first JSON property sent.
//
// Both are derived, never hand-edited: change the server, regenerate the wire models, then run `npm run generate`.
// `node scripts/generate-models.mjs --check` exits 1 when the committed files are stale (a unit test runs the same
// comparison).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HEADER = [
  "// <auto-generated>",
  "// Generated by scripts/generate-models.mjs from ../models.json and ../routes.json.",
  "// Do not edit: regenerate the wire models (maitento/app/SdkModelGenerator), then run `npm run generate`.",
  "// </auto-generated>",
];

const PRIMITIVES = new Set(["string", "boolean", "integer", "number", "uuid", "datetime", "date", "time", "timespan", "base64", "any"]);

/** Parses the language-neutral type notation of models.json / routes.json (`T[]`, `map<string, T>`, `T | null`). */
export function parseWireType(text) {
  const s = text.trim();
  const union = splitTopLevel(s, " | ");
  if (union.length > 1) {
    const rest = union.filter((part) => part !== "null");
    if (rest.length !== 1 || union.length !== 2) {
      throw new Error(`Unsupported union in wire type: ${text}`);
    }
    return { kind: "nullable", element: parseWireType(rest[0]) };
  }
  if (s.endsWith("[]")) {
    let inner = s.slice(0, -2);
    if (inner.startsWith("(") && inner.endsWith(")")) {
      inner = inner.slice(1, -1);
    }
    return { kind: "array", element: parseWireType(inner) };
  }
  if (s.startsWith("map<string, ") && s.endsWith(">")) {
    return { kind: "map", element: parseWireType(s.slice("map<string, ".length, -1)) };
  }
  if (PRIMITIVES.has(s)) {
    return { kind: "primitive", name: s };
  }
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(s)) {
    throw new Error(`Unsupported wire type: ${text}`);
  }
  return { kind: "named", name: s };
}

function splitTopLevel(text, separator) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === "<" || c === "(") depth++;
    else if (c === ">" || c === ")") depth--;
    else if (depth === 0 && text.startsWith(separator, i)) {
      parts.push(text.slice(start, i));
      start = i + separator.length;
      i += separator.length - 1;
    }
  }
  parts.push(text.slice(start));
  return parts;
}

/** Every emitted shape (interface or union type) of the wire models, by the name the TypeScript emitter gave it. */
export function collectShapes(models) {
  const byName = new Map(models.map((m) => [m.name, m]));
  const requestName = (model) => (model.response && model.inputVariant ? model.inputVariant : model.name);
  const shapes = new Map();
  const add = (name, model, usage) => {
    if (shapes.has(name)) {
      throw new Error(`Two shapes are named ${name}`);
    }
    if (model.kind === "union") {
      const members = model.members.map((member) => {
        const target = byName.get(member.type);
        if (!target) throw new Error(`Union ${model.name} names unknown member ${member.type}`);
        return { value: member.value, shape: usage === "response" ? target.name : requestName(target) };
      });
      shapes.set(name, { name, model, usage, kind: "union", discriminator: model.discriminator, members });
      return;
    }
    const properties = (model.properties ?? [])
      .filter((p) => (usage === "response" ? p.responseType : p.requestType))
      .map((p) => ({
        name: p.name,
        type: parseWireType(usage === "response" ? p.responseType : p.requestType),
        optional: usage === "response" ? Boolean(p.mayBeOmitted) : !p.required,
        readOnly: usage === "response" && Boolean(p.readOnly),
        description: p.description ?? null,
      }));
    shapes.set(name, {
      name,
      model,
      usage,
      kind: "object",
      discriminator: model.discriminator ?? null,
      properties,
    });
  };
  for (const model of models) {
    if (model.kind === "enum") continue;
    if (model.response) {
      add(model.name, model, "response");
      if (model.inputVariant) add(model.inputVariant, model, "request");
    } else {
      add(model.name, model, "request");
    }
  }
  return shapes;
}

function fixpoint(shapes, isDirect, typeQualifies) {
  const result = new Set();
  let changed = true;
  while (changed) {
    changed = false;
    for (const shape of shapes.values()) {
      if (result.has(shape.name)) continue;
      const qualifies =
        isDirect(shape) ||
        (shape.kind === "union"
          ? shape.members.some((m) => result.has(m.shape))
          : shape.properties.some((p) => typeQualifies(p.type, result)));
      if (qualifies) {
        result.add(shape.name);
        changed = true;
      }
    }
  }
  return result;
}

function refersTo(type, set, primitives) {
  switch (type.kind) {
    case "primitive":
      return primitives.has(type.name);
    case "named":
      return set.has(type.name);
    default:
      return refersTo(type.element, set, primitives);
  }
}

const CONVERTED = new Set(["datetime", "timespan"]);

/** The shapes whose SDK type differs from the wire type (they carry dates or TimeSpans, here or nested). */
export function viewShapes(shapes) {
  return fixpoint(shapes, () => false, (type, set) => refersTo(type, set, CONVERTED));
}

/** The shapes the runtime codec has to visit: view shapes plus everything that carries a discriminator. */
export function codecShapes(shapes) {
  return fixpoint(
    shapes,
    (shape) => shape.kind === "union" || Boolean(shape.discriminator),
    (type, set) => refersTo(type, set, CONVERTED),
  );
}

function tsType(type, usage, views) {
  switch (type.kind) {
    case "nullable":
      return `${tsType(type.element, usage, views)} | null`;
    case "array": {
      const element = tsType(type.element, usage, views);
      return element.includes(" ") ? `(${element})[]` : `${element}[]`;
    }
    case "map":
      return `Record<string, ${tsType(type.element, usage, views)}>`;
    case "named":
      return views.has(type.name) ? type.name : `W.${type.name}`;
    default:
      switch (type.name) {
        case "datetime":
          return usage === "response" ? "Date" : "Date | string";
        case "timespan":
          return usage === "response" ? "number" : "number | W.DotNetTimeSpan";
        case "boolean":
          return "boolean";
        case "integer":
        case "number":
          return "number";
        case "any":
          return "unknown";
        default:
          return "string";
      }
  }
}

function scalarNote(type, usage) {
  const seen = new Set();
  const walk = (t) => {
    if (t.kind === "primitive") seen.add(t.name);
    else if (t.kind !== "named") walk(t.element);
  };
  walk(type);
  const notes = [];
  if (seen.has("datetime")) {
    notes.push(usage === "response" ? "A `Date` (ISO-8601 on the wire)." : "A `Date` or an ISO-8601 string.");
  }
  if (seen.has("timespan")) {
    notes.push(
      usage === "response"
        ? "Milliseconds (a .NET TimeSpan on the wire)."
        : "Milliseconds, or a .NET TimeSpan string (`\"00:05:00\"`); sent as a .NET TimeSpan.",
    );
  }
  return notes;
}

function jsDoc(lines, indent, text, notes) {
  const all = [];
  if (text) all.push(...text.split("\n"));
  if (notes.length) {
    if (all.length) all.push("");
    all.push(...notes);
  }
  if (!all.length) return;
  const safe = all.map((l) => l.replace(/\*\//g, "*\\/"));
  if (safe.length === 1) {
    lines.push(`${indent}/** ${safe[0]} */`);
    return;
  }
  lines.push(`${indent}/**`);
  for (const l of safe) lines.push(l.length ? `${indent} * ${l}` : `${indent} *`);
  lines.push(`${indent} */`);
}

function propertyKey(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function payloadMaps(lines, routes, views, shapes) {
  const ref = (name) => {
    if (!shapes.has(name)) throw new Error(`Payload type ${name} is not a model`);
    return views.has(name) ? name : `W.${name}`;
  };
  lines.push("");
  jsDoc(lines, "", "The `message` of each `/notifications` WebSocket frame, by event name, as the SDK delivers it.", []);
  lines.push("export interface NotificationEventPayloads {");
  for (const event of [...routes.events].sort((a, b) => (a.name < b.name ? -1 : 1))) {
    jsDoc(lines, "  ", event.description, [`Scope: ${event.scope}.`]);
    lines.push(`  ${JSON.stringify(event.name)}: ${event.payloadType ? ref(event.payloadType) : "Record<string, never>"};`);
  }
  lines.push("}");
  lines.push("");
  lines.push("/** The name of a `/notifications` event. */");
  lines.push("export type NotificationEventName = keyof NotificationEventPayloads;");
  lines.push("");
  jsDoc(lines, "", "The body of a web-hook delivery (a `PUT` of the entity's current state), by its `X-MT-WebHook-Type` header.", []);
  lines.push("export interface WebHookPayloads {");
  for (const hook of [...routes.webhooks].sort((a, b) => (a.type < b.type ? -1 : 1))) {
    lines.push(`  ${propertyKey(hook.type)}: ${ref(hook.payloadType)};`);
  }
  lines.push("}");
}

function modelsFile(shapes, views, routes) {
  const lines = [...HEADER, ""];
  lines.push('import type * as W from "./generated/index.js";');
  const plain = [...shapes.keys()].filter((name) => !views.has(name)).sort();
  lines.push("");
  lines.push("// Models with nothing to convert: exactly the wire models.");
  lines.push("export type {");
  for (const name of plain) lines.push(`  ${name},`);
  lines.push('} from "./generated/index.js";');

  for (const name of [...views].sort()) {
    const shape = shapes.get(name);
    lines.push("");
    if (shape.kind === "union") {
      jsDoc(lines, "", shape.model.description ?? null, [`Discriminated by \`${shape.discriminator}\`.`]);
      lines.push(`export type ${name} =`);
      shape.members.forEach((m, i) => {
        const member = views.has(m.shape) ? m.shape : `W.${m.shape}`;
        lines.push(`  | ${member}${i === shape.members.length - 1 ? ";" : ""}`);
      });
      continue;
    }
    const overridden = shape.properties.filter((p) => refersTo(p.type, views, CONVERTED));
    jsDoc(lines, "", shape.model.description ?? null, []);
    const omitted = overridden.map((p) => JSON.stringify(p.name)).join(" | ");
    lines.push(`export interface ${name} extends Omit<W.${name}, ${omitted}> {`);
    for (const p of overridden) {
      jsDoc(lines, "  ", p.description, scalarNote(p.type, shape.usage));
      const modifiers = p.readOnly ? "readonly " : "";
      lines.push(`  ${modifiers}${propertyKey(p.name)}${p.optional ? "?" : ""}: ${tsType(p.type, shape.usage, views)};`);
    }
    lines.push("}");
  }
  payloadMaps(lines, routes, views, shapes);
  return lines.join("\n") + "\n";
}

function describe(type) {
  switch (type.kind) {
    case "nullable":
      return describe(type.element);
    case "array": {
      const e = describe(type.element);
      return e.includes(" ") ? `(${e})[]` : `${e}[]`;
    }
    case "map":
      return `map<string, ${describe(type.element)}>`;
    case "named":
      return type.name;
    default:
      return type.name;
  }
}

function codecFile(shapes, codecs, routes) {
  const lines = [...HEADER, ""];
  lines.push('import type { CodecTable } from "./core/codec.js";');
  lines.push("");
  lines.push("/**");
  lines.push(" * Per model, the fields the codec converts: `d` lists the discriminator (property, value) to write first;");
  lines.push(" * `f` maps a field to its wire type (only fields that hold a date, a TimeSpan or a model the codec visits);");
  lines.push(" * `u` is a union's discriminator property and its members by discriminator value.");
  lines.push(" */");
  lines.push("export const CODEC_TABLE: CodecTable = {");
  for (const name of [...codecs].sort()) {
    const shape = shapes.get(name);
    if (shape.kind === "union") {
      const members = Object.fromEntries(shape.members.map((m) => [m.value, m.shape]));
      lines.push(`  ${name}: { u: [${JSON.stringify(shape.discriminator)}, ${JSON.stringify(members)}] },`);
      continue;
    }
    const fields = {};
    for (const p of shape.properties) {
      if (refersTo(p.type, codecs, CONVERTED)) fields[p.name] = describe(p.type);
    }
    const parts = [];
    if (shape.discriminator) {
      parts.push(`d: [${JSON.stringify(shape.discriminator.property)}, ${JSON.stringify(shape.discriminator.value)}]`);
    }
    if (Object.keys(fields).length) parts.push(`f: ${JSON.stringify(fields)}`);
    lines.push(`  ${name}: { ${parts.join(", ")} },`);
  }
  lines.push("};");
  lines.push("");
  lines.push("/** The payload model of each `/notifications` event (null: no payload). */");
  lines.push("export const EVENT_PAYLOAD_TYPES: Readonly<Record<string, string | null>> = {");
  for (const event of [...routes.events].sort((a, b) => (a.name < b.name ? -1 : 1))) {
    lines.push(`  ${JSON.stringify(event.name)}: ${JSON.stringify(event.payloadType)},`);
  }
  lines.push("};");
  lines.push("");
  lines.push("/** The payload model of each web-hook type (the `X-MT-WebHook-Type` header). */");
  lines.push("export const WEBHOOK_PAYLOAD_TYPES: Readonly<Record<string, string>> = {");
  for (const hook of [...routes.webhooks].sort((a, b) => (a.type < b.type ? -1 : 1))) {
    lines.push(`  ${propertyKey(hook.type)}: ${JSON.stringify(hook.payloadType)},`);
  }
  lines.push("};");
  return lines.join("\n") + "\n";
}

/** Checks the shape names derived here are exactly the interfaces/types the wire emitter wrote. */
function assertMatchesWireModels(shapes, wireModelsTs) {
  const declared = new Set();
  for (const match of wireModelsTs.matchAll(/^export (?:interface|type) (\w+)/gm)) declared.add(match[1]);
  for (const name of ["NotificationEventPayloads", "NotificationEventName", "WebHookPayloads"]) declared.delete(name);
  const missing = [...shapes.keys()].filter((n) => !declared.has(n));
  const extra = [...declared].filter((n) => !shapes.has(n));
  if (missing.length || extra.length) {
    throw new Error(
      `models.json and src/generated/models.ts disagree. Not in models.ts: ${missing.join(", ") || "-"}; ` +
        `not derived from models.json: ${extra.join(", ") || "-"}. Regenerate the wire models.`,
    );
  }
}

/** Produces the generated files' contents, keyed by path relative to the package root. */
export function generate(packageRoot) {
  const sdksRoot = join(packageRoot, "..");
  const models = JSON.parse(readFileSync(join(sdksRoot, "models.json"), "utf8")).models;
  const routes = JSON.parse(readFileSync(join(sdksRoot, "routes.json"), "utf8"));
  const wireModelsTs = readFileSync(join(packageRoot, "src", "generated", "models.ts"), "utf8");
  const shapes = collectShapes(models);
  assertMatchesWireModels(shapes, wireModelsTs);
  const views = viewShapes(shapes);
  const codecs = codecShapes(shapes);
  return {
    "src/models.ts": modelsFile(shapes, views, routes),
    "src/codec-table.ts": codecFile(shapes, codecs, routes),
  };
}

const isMain =
  Boolean(process.argv[1]) && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase();
if (isMain) {
  const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
  const check = process.argv.includes("--check");
  const files = generate(packageRoot);
  let stale = 0;
  for (const [path, content] of Object.entries(files)) {
    const full = join(packageRoot, path);
    if (check) {
      let current = null;
      try {
        current = readFileSync(full, "utf8").replace(/\r\n/g, "\n");
      } catch {
        // missing counts as stale
      }
      if (current !== content) {
        console.error(`stale: ${path}`);
        stale++;
      }
    } else {
      writeFileSync(full, content);
      console.log(`wrote ${path}`);
    }
  }
  if (stale) {
    console.error("Run `npm run generate` and commit the result.");
    process.exit(1);
  }
}

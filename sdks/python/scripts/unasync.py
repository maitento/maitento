"""Generates the blocking client (``src/maitento/_sync``) from the asyncio one (``src/maitento/_async``).

The SDK is written once, in async form; this rewrites tokens (``async def`` -> ``def``, ``await x`` -> ``x``,
``AsyncFoo`` -> ``Foo``, ``_aio`` -> ``_sio``, ...) so the two surfaces cannot drift. ``tests/test_unasync.py``
fails when a committed ``_sync`` file differs from what this produces.

    python scripts/unasync.py          # regenerate
    python scripts/unasync.py --check  # exit 1 if anything is stale

The event streams (``_events.py``) are hand-written in both folders: the blocking one uses a reader thread.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASYNC_DIR = ROOT / "src" / "maitento" / "_async"
SYNC_DIR = ROOT / "src" / "maitento" / "_sync"
FILES = ("__init__.py", "_client.py", "_paging.py", "_resources.py", "_run.py", "_transport.py")

HEADER = (
    "# <auto-generated>\n"
    "# Generated by scripts/unasync.py from src/maitento/_async/{name}. Do not edit: change the async source, then\n"
    "# run `python scripts/unasync.py`.\n"
    "# </auto-generated>\n"
)

_SUBSTITUTIONS = [
    (re.compile(r"\basync def\b"), "def"),
    (re.compile(r"\basync with\b"), "with"),
    (re.compile(r"\basync for\b"), "for"),
    (re.compile(r"\bawait\s+"), ""),
    (re.compile(r"\b__aenter__\b"), "__enter__"),
    (re.compile(r"\b__aexit__\b"), "__exit__"),
    (re.compile(r"\b__aiter__\b"), "__iter__"),
    (re.compile(r"\b__anext__\b"), "__next__"),
    (re.compile(r"\bStopAsyncIteration\b"), "StopIteration"),
    (re.compile(r"\baclose\b"), "close"),
    (re.compile(r"\b_aio\b"), "_sio"),
    (re.compile(r"\basyncio\b"), "blocking"),
    (re.compile(r"\bAsync(?=[A-Z])"), ""),
]


def _strip_awaitable(text: str) -> str:
    """``Awaitable[X]`` -> ``X``, for any (bracket-balanced) ``X``."""
    marker = "Awaitable["
    out = []
    index = 0
    while True:
        found = text.find(marker, index)
        if found < 0 or (found > 0 and (text[found - 1].isalnum() or text[found - 1] == "_")):
            if found < 0:
                out.append(text[index:])
                return "".join(out)
            out.append(text[index : found + len(marker)])
            index = found + len(marker)
            continue
        out.append(text[index:found])
        depth = 1
        cursor = found + len(marker)
        while depth:
            char = text[cursor]
            if char == "[":
                depth += 1
            elif char == "]":
                depth -= 1
            cursor += 1
        out.append(text[found + len(marker) : cursor - 1])
        index = cursor


def _drop_unused_awaitable_import(text: str) -> str:
    """Removes ``Awaitable`` from the ``typing`` import once nothing else uses it."""
    lines = text.split("\n")
    used = any(re.search(r"\bAwaitable\b", line) for line in lines if not line.startswith("from typing import"))
    if used:
        return text
    for index, line in enumerate(lines):
        if line.startswith("from typing import"):
            lines[index] = re.sub(r"\bAwaitable, |, Awaitable\b", "", line)
    return "\n".join(lines)


def transform(source: str, name: str) -> str:
    text = _strip_awaitable(source)
    for pattern, replacement in _SUBSTITUTIONS:
        text = pattern.sub(replacement, text)
    text = _drop_unused_awaitable_import(text)
    return HEADER.format(name=name) + text


def generate() -> dict[str, str]:
    return {name: transform((ASYNC_DIR / name).read_text(encoding="utf-8"), name) for name in FILES}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    args = parser.parse_args()
    stale = []
    for name, text in generate().items():
        target = SYNC_DIR / name
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        stale.append(name)
        if not args.check:
            target.write_text(text, encoding="utf-8", newline="\n")
    if args.check and stale:
        print(f"stale: {', '.join(stale)} (run python scripts/unasync.py)", file=sys.stderr)
        return 1
    print("up to date" if not stale else f"regenerated: {', '.join(stale)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

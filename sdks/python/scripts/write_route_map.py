"""Writes ``route-map.json`` (for the docs generator) from ``maitento._route_map``.

    python scripts/write_route_map.py          # regenerate
    python scripts/write_route_map.py --check  # exit 1 if the committed file is stale

Each route of ``maitento/public/sdks/routes.json`` with ``sdk: true`` appears once, either in ``routes`` (the Python
method that reaches it and a one-line example) or in ``excluded`` (with the reason).
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "route-map.json"


def _load(name: str) -> Any:
    """Loads one module file of the package without importing the package (so no dependencies are needed)."""
    spec = importlib.util.spec_from_file_location(f"_route_map_script_{name}", ROOT / "src" / "maitento" / f"{name}.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render() -> str:
    route_map = _load("_route_map")
    version = _load("_version").__version__
    document = {
        "$comment": "Generated by maitento/public/sdks/python/scripts/write_route_map.py from src/maitento/_route_map.py. Do not edit.",
        "language": "python",
        "package": "maitento",
        "version": version,
        "client": "mt = Maitento()",
        "routes": route_map.ROUTES,
        "excluded": route_map.EXCLUDED,
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when route-map.json is stale")
    args = parser.parse_args()
    text = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if current == text:
        print("up to date")
        return 0
    if args.check:
        print("route-map.json is stale (run python scripts/write_route_map.py)", file=sys.stderr)
        return 1
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
